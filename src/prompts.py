def build_prompt_toc(org_config: dict) -> str:
    """목차 프롬프트"""
    section_filter = org_config.get("목차", {}).get("섹션필터", "모든 조사 항목을 찾아주세요.")
    return PROMPT_TOC.format(section_filter=section_filter)


def build_prompt_metadata(org_config: dict, survey_type: str = "전국") -> str:
    """메타데이터 프롬프트"""
    fields = org_config.get("메타데이터", {}).get("필드", [
        "표본크기", "표본오차", "조사방법", "조사기간", "조사기관", "응답률"
    ])
    
    # 지방 조사일 때만 지역 필드 추가
    if survey_type == "지방":
        region_field = REGION_FIELD_RULE
    else:
        region_field = ""
    
    return PROMPT_METADATA.format(
        metadata_fields="\n".join(f"- {f}" for f in fields),
        region_field=region_field
    )


def build_prompt_region(org_config: dict) -> str:
    """권역 프롬프트"""
    return PROMPT_REGION


