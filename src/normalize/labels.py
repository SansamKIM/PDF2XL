def apply_term_mapping(obj: object, mapping: Dict[str, str]):
    """YAML에 정의된 기관별 용어 매핑을 임의의 JSON 유사 객체에 적용.

    추출된 표 JSON은 dict/list/str가 중첩된 구조다. 용어 매핑은 다음에 적용돼야 한다:
      - 문자열 값(예: 질문/항목명/응답항목 요소)
      - "데이터" 내부의 동적 dict 키(행 라벨 / 응답 라벨)

    참고: 결정적이고 보수적으로 동작하도록 설계
      - 문자열이 아닌 스칼라(int/float/bool/None)는 그대로 반환
      - 키 매핑 충돌 시 가능한 한 병합(None이 아닌 값/나중 값 우선)
    """
    if not mapping or obj is None:
        return obj

    # 문자열 빠른 경로
    if isinstance(obj, str):
        s = str(obj)

        # 더 긴 키를 먼저 적용해 부분 덮어쓰기를 줄임
        items = sorted(mapping.items(), key=lambda kv: len(str(kv[0])), reverse=True)

        for k, v in items:
            if not k:
                continue

            k_str = str(k)
            v_str = "" if v is None else str(v)

            # 정규식용 이스케이프
            pat = re.escape(k_str)

            # 한글/라틴/숫자 경계를 넣어 더 긴 토큰이 손상되지 않도록 함
            if re.search(r"^[가-힣0-9A-Za-z]", k_str):
                pat = r"(?<![가-힣0-9A-Za-z])" + pat
            if re.search(r"[가-힣0-9A-Za-z]$", k_str):
                pat = pat + r"(?![가-힣0-9A-Za-z])"

            try:
                s = re.sub(pat, v_str, s)
            except re.error:
                # 최후 폴백
                s = s.replace(k_str, v_str)

        return s

    # 리스트/튜플: 각 원소 매핑
    if isinstance(obj, list):
        return [apply_term_mapping(x, mapping) for x in obj]

    # 딕셔너리: 키/값 모두 매핑
    if isinstance(obj, dict):
        def _merge(a, b):
            if a is None:
                return b
            if b is None:
                return a
            if isinstance(a, dict) and isinstance(b, dict):
                out = dict(a)
                for kk, vv in b.items():
                    if kk in out:
                        out[kk] = _merge(out[kk], vv)
                    else:
                        out[kk] = vv
                return out
            if isinstance(a, list) and isinstance(b, list):
                return a + b
            # 폴백: 이후 값(b) 우선
            return b

        out = {}
        for k, v in obj.items():
            new_k = apply_term_mapping(k, mapping) if isinstance(k, str) else k
            new_v = apply_term_mapping(v, mapping)
            if new_k in out:
                out[new_k] = _merge(out[new_k], new_v)
            else:
                out[new_k] = new_v
        return out

    # 기타 타입은 그대로 반환
    return obj


_HANGUL_RE = re.compile(r"^[가-힣]$")


def _join_spaced_hangul(segment: str) -> str:
    """모든 토큰이 한글 음절일 때 '주 부' -> '주부'처럼 붙여줌.

    일부 기관 표에서 세로/띄어쓰기 라벨을 보정하기 위한 용도.
    """
    if not isinstance(segment, str):
        return segment
    toks = segment.split()
    if len(toks) >= 2 and all(_HANGUL_RE.match(t) for t in toks):
        return "".join(toks)
    return segment


def _normalize_separators(s: str) -> str:
    # 흔한 구분자 및 유니코드 변형을 정규화
    s = s.replace("_", " ")
    # 점을 슬래시로 통일(기관에 따라 '·'를 구분자로 씀)
    for ch in ("·", "ㆍ", "∙", "•", "／"):
        s = s.replace(ch, "/")
    # 물결표(~) 변형
    for ch in ("∼", "〜", "～"):
        s = s.replace(ch, "~")
    # 마이너스(-) 변형
    for ch in ("－", "—", "–"):
        s = s.replace(ch, "-")
    return s


_AGE_RANGE_RE = re.compile(r"^(\d{1,2})[~-](\d{1,2})(?:세)?$")  # 18~29, 18-29세 등
_AGE_DECADE_RE = re.compile(r"^(\d{2})대$")
_AGE_OVER_RE = re.compile(r"^(\d{2})세이상$")


def normalize_label(text: str) -> str:
    """단일 범주 라벨(행 키) 정규화.

    엑셀 템플릿 행 매핑과 최대한 맞도록 키를 만듭니다.
    """
    if text is None:
        return text

    s = str(text).strip()
    if not s:
        return s

    s = _normalize_separators(s)

    # 공백을 먼저 정리
    s = re.sub(r"\s+", " ", s).strip()

    # 표에서 자주 쓰는 괄호 제거(예: [ 서울 ])
    for ch in ["[", "]", "【", "】"]:
        s = s.replace(ch, "")

    # 구분자 주변 공백 정리
    s = re.sub(r"\s*/\s*", "/", s)
    s = re.sub(r"\s*~\s*", "~", s)
    s = re.sub(r"\s*-\s*", "-", s)
    s = re.sub(r"\s*\(\s*", "(", s)
    s = re.sub(r"\s*\)\s*", ")", s)

    # 일부 PDF가 지역 라벨 끝에 슬래시를 붙여 '인천 경기 /', '부산 울산 경남 / /'처럼 나오기도 함.
    # 구분자 정규화 후에는 '.../' 또는 '...//'처럼 보이므로 끝 슬래시를 제거.
    s = re.sub(r"/+$", "", s).strip()


    # 세그먼트별로 띄어 쓴 한글 음절을 붙이기(예: '모 름/무 응 답', '주 부', '학 생')
    def _join_seg(seg: str) -> str:
        # 괄호 컨텍스트는 유지하면서 본문/컨텍스트의 한글 띄어쓰기는 붙이기
        seg = (seg or "").strip()
        if "(" in seg and seg.endswith(")"):
            base, ctx = seg.split("(", 1)
            ctx_body = ctx[:-1]  # 끝의 ')' 제거
            base = _join_spaced_hangul(base.strip())
            ctx_body = _join_spaced_hangul(ctx_body.strip())
            return base + "(" + ctx_body + ")"
        return _join_spaced_hangul(seg)

    if "/" in s:
        s = "/".join(_join_seg(seg) for seg in s.split("/"))
    else:
        s = _join_seg(s)

    # (①+②) 같은 결합 지표 접미어 제거
    s = re.sub(
        r"\s*\(\s*[0-9①②③④⑤⑥⑦⑧⑨⑩⑪⑫⑬⑭⑮⑯⑰⑱⑲⑳]+\s*\+\s*"
        r"[0-9①②③④⑤⑥⑦⑧⑨⑩⑪⑫⑬⑭⑮⑯⑰⑱⑲⑳]+\s*\)\s*$",
        "",
        s,
    ).strip()

    # 명시적 결합 라벨
    if re.fullmatch(r"없음\s*/\s*모름", s):
        s = "없음/모름"

    # --- 특수: 컨텍스트가 붙은 모름/무응답(삭제 금지, 결정적으로 매핑) ---
    # 예시:
    # - 모름/무응답(직업) -> 모름/무응답(직업)  (컨텍스트 유지: 다른 분류의 '모름/무응답'과 충돌 방지)
    # - 모름/무응답(이념성향) -> 모름.무응답
    m_ctx = re.match(r"^(?P<base>[^()]+)\((?P<ctx>[^)]+)\)$", s)
    if m_ctx:
        base = m_ctx.group("base").strip()
        ctx = m_ctx.group("ctx").strip()

        base_norm = LABEL_ALIASES.get(base, base)

        if any(k in ctx for k in ["직업"]):
            if base_norm in {"모름.무응답", "잘 모름", "무응답"} or base in {"모름/무응답", "무응답", "모름/기타"}:
                return "모름/무응답(직업)"

        if any(k in ctx for k in ["이념", "이념성향", "정치성향", "정치적성향", "정치 성향"]):
            if base_norm in {"모름.무응답", "잘 모름", "무응답"} or base in {"모름/무응답", "무응답", "모름/기타"}:
                return "모름.무응답"

    # 그룹 접두어 제거: "직업: 자영업" -> "자영업"
    # 참고(지방 권역 라벨):
    # - '권역1', '권역 1' 같은 실제 행 라벨은 **그대로 유지**해야 합니다.
    # - 과거 정규화 규칙에서 '권역'을 그룹 접두어로 간주해 제거하면서
    #   '권역1' -> '1'로 변환되어 지역 행이 템플릿 매핑에서 누락되는 문제가 있었습니다.
    # - 따라서 '권역'은 뒤에 숫자(공백 포함)가 오는 경우에는 접두어로 제거하지 않습니다.
    m = re.match(
        r"^(?:이념성향별?|정치적\s*성향별?|정치\s*성향별?|정치성향별?|직업별?|지역|지역별|권역별|권역(?!\s*\d)|성별|연령별?|연령)\s*[:\-]?\s*(.+거주)$",
        s,
    )
    if m:
        s = m.group(1).strip()

    # --- 연령 정규화 ---
    # 18 ~ 29 세 / 18~29 / 18-29세 -> 18~29세
    s_no_space = s.replace(" ", "")
    m_age = _AGE_RANGE_RE.match(s_no_space)
    if m_age:
        a, b = m_age.group(1), m_age.group(2)
        # 범위 구분자를 '~'로 통일하고 '세' 추가
        s = f"{int(a)}~{int(b)}세"
        return LABEL_ALIASES.get(s, s)

    # 30 대 -> 30대
    m_dec = re.match(r"^(\d{2})\s*대$", s)
    if m_dec:
        s = f"{m_dec.group(1)}대"
        return LABEL_ALIASES.get(s, s)

    # 70 세 이상 / 70세이상 -> 70세 이상
    m_over = re.match(r"^(\d{2})\s*세\s*이상$", s)
    if m_over:
        s = f"{m_over.group(1)}세 이상"
        return LABEL_ALIASES.get(s, s)
    m_over2 = _AGE_OVER_RE.match(s_no_space)
    if m_over2:
        s = f"{m_over2.group(1)}세 이상"
        return LABEL_ALIASES.get(s, s)

    # --- 지역 정규화(공통 순서 보정) ---
    # 대전/세종/충청이 어떤 순서/축약으로든 포함되면
    if ("대전" in s) and ("세종" in s) and (("충청" in s) or ("/충/" in s) or ("충" in s and "충청" not in s)):
        # 흔한 비정규 형태: 대전/충/세종, 대전/충청(세종), 대전/충청/세종
        if any(x in s for x in ["대전/충/세종", "대전/충청/세종", "대전/충청(세종)"]):
            return "대전/세종/충청"

    # 최종 별칭 조회
    return LABEL_ALIASES.get(s, s)
